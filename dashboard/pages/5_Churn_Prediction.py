# MANUAL CHURN ESTIMATOR
# ==========================================================

st.header("🧮 Quick Churn Estimator")

st.caption(
    "A simplified, illustrative estimate based on the same behavioural "
    "features used to train the model."
)

i1, i2 = st.columns(2)

with i1:

    input_recency = st.number_input(
        "Recency (days)",
        value=30.0,
    )

    input_frequency = st.number_input(
        "Frequency",
        value=5.0,
    )

    input_monetary = st.number_input(
        "Monetary Value",
        value=5000.0,
    )

with i2:

    input_cancellation_rate = st.slider(
        "Cancellation Rate",
        0.0,
        1.0,
        0.0,
    )

    input_active_months = st.number_input(
        "Active Months",
        value=12.0,
    )

    input_weekend_rate = st.slider(
        "Weekend Purchase Rate",
        0.0,
        1.0,
        0.20,
    )

if st.button("Estimate Churn Risk"):

    estimated_probability = (
        0.40 * (input_recency / 365)
        + 0.30 * input_cancellation_rate
        + 0.20 * (1 / (input_frequency + 1))
        + 0.10 * (1 / (input_active_months + 1))
    )

    estimated_probability = max(0, min(estimated_probability, 1))

    if estimated_probability >= 0.7:

        estimated_status = "High Risk"

        estimated_tone = st.error

    elif estimated_probability >= 0.4:

        estimated_status = "Medium Risk"

        estimated_tone = st.warning

    else:

        estimated_status = "Low Risk"

        estimated_tone = st.success

    r1, r2 = st.columns(2)

    with r1:

        st.metric(
            "Estimated Probability",
            f"{estimated_probability:.1%}",
        )

    with r2:

        st.metric(
            "Risk Category",
            estimated_status,
        )

    estimated_tone(
        f"This customer falls into the **{estimated_status}** bucket "
        f"based on the current thresholds."
    )

