# MANUAL CLV ESTIMATOR
# ==========================================================

st.header("🧮 Quick CLV Estimator")

st.caption(
    "A simplified, illustrative estimate based on the same behavioural "
    "features used to train the model."
)

i1, i2, i3, i4 = st.columns(4)

with i1:

    input_recency = st.number_input(
        "Recency (days)",
        value=30.0,
    )

with i2:

    input_frequency = st.number_input(
        "Frequency",
        value=5.0,
    )

with i3:

    input_monetary = st.number_input(
        "Monetary Value",
        value=5000.0,
    )

with i4:

    input_unique_products = st.number_input(
        "Unique Products",
        value=10.0,
    )

if st.button("Estimate CLV"):

    estimate = (
        0.4 * input_monetary
        + 0.25 * input_frequency * 100
        + 0.15 * input_unique_products * 50
        - 0.1 * input_recency * 10
    )

    estimate = max(estimate, 0)

    if estimate >= high_value_cutoff:

        estimate_category = "High Value"

        estimate_tone = st.success

    elif estimate >= medium_value_cutoff:

        estimate_category = "Medium Value"

        estimate_tone = st.warning

    else:

        estimate_category = "Low Value"

        estimate_tone = st.error

    r1, r2 = st.columns(2)

    with r1:

        st.metric(
            "Estimated CLV",
            format_currency(estimate),
        )

    with r2:

        st.metric(
            "Category",
            estimate_category,
        )

    estimate_tone(
        f"This customer falls into the **{estimate_category}** bucket "
        f"based on the current value thresholds."
    )

