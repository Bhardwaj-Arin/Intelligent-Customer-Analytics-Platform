"""
Customer Lifetime Value (CLV) Prediction Dashboard
------------------------------------------------------------

Explores predicted Customer Lifetime Value, generated by a
Gradient Boosting regression model.

Project: Intelligent Customer Analytics Platform
"""

import plotly.express as px
import streamlit as st

from utils.cache import load_csv
from utils.config import CLV_ARTIFACTS_DIR, PROCESSED_DATA_DIR
from utils.helper import format_currency

# ==========================================================
# LOAD DATA
# ==========================================================

prediction_df = load_csv(
    PROCESSED_DATA_DIR / "customer_clv_predictions.csv"
)

metrics_df = load_csv(CLV_ARTIFACTS_DIR / "regression_metrics.csv")
metrics = dict(zip(metrics_df["Metric"], metrics_df["Value"]))

importance_df = load_csv(CLV_ARTIFACTS_DIR / "feature_importance.csv")

# ==========================================================
# PAGE HEADER
# ==========================================================

st.title("💰 Customer Lifetime Value Prediction")

st.markdown(
    """
This model predicts each customer's future **Customer Lifetime
Value (CLV)** — an estimate of how much revenue they'll generate
going forward — using a **Gradient Boosting Regressor** trained on
their past purchase behaviour.
"""
)

st.divider()

# ==========================================================
# MODEL PERFORMANCE
# ==========================================================

st.header("📈 Model Performance")

m1, m2, m3 = st.columns(3)
m1.metric("MAE", format_currency(float(metrics["MAE"])))
m2.metric("RMSE", format_currency(float(metrics["RMSE"])))
m3.metric("R² Score", f"{float(metrics['R2']):.3f}")

st.caption(
    "**MAE** — on average, predictions are off by this amount. "
    "**R²** close to 0 means the model isn't explaining much more "
    "variance than simply predicting the average CLV for everyone — "
    "customer spend in this dataset is highly irregular (many "
    "one-time buyers), which makes it a genuinely hard regression "
    "problem, not a bug."
)

st.divider()

# ==========================================================
# CLV OVERVIEW
# ==========================================================

st.header("📌 CLV Overview")

k1, k2, k3 = st.columns(3)
k1.metric("Customers", f"{len(prediction_df):,}")
k2.metric(
    "Avg. Predicted CLV",
    format_currency(prediction_df["PredictedCLV"].mean()),
)
k3.metric(
    "Total Predicted CLV",
    format_currency(prediction_df["PredictedCLV"].sum()),
)

st.divider()

# ==========================================================
# ACTUAL VS PREDICTED
# ==========================================================

st.header("🎯 Actual vs. Predicted CLV")

sample_df = prediction_df.sample(
    min(1500, len(prediction_df)), random_state=42
)

fig_scatter = px.scatter(
    sample_df,
    x="CLV",
    y="PredictedCLV",
    opacity=0.5,
)
fig_scatter.add_shape(
    type="line",
    x0=sample_df["CLV"].min(),
    y0=sample_df["CLV"].min(),
    x1=sample_df["CLV"].max(),
    y1=sample_df["CLV"].max(),
    line=dict(dash="dash"),
)
fig_scatter.update_layout(height=420, margin=dict(l=10, r=10, t=10, b=10))
st.plotly_chart(fig_scatter, use_container_width=True)

st.caption(
    "Points on the dashed line would be perfect predictions. The "
    "spread shows where the model over- or under-estimates."
)

st.divider()

# ==========================================================
# WHAT DRIVES CLV
# ==========================================================

st.header("⚙️ What Drives Predicted CLV")

top_features = importance_df.sort_values(
    "Importance", ascending=False
).head(8)

fig_importance = px.bar(
    top_features,
    x="Importance",
    y="Feature",
    orientation="h",
)
fig_importance.update_layout(
    height=340,
    yaxis=dict(autorange="reversed"),
    margin=dict(l=10, r=10, t=10, b=10),
)
st.plotly_chart(fig_importance, use_container_width=True)

st.caption(
    "**Monetary** (past total spend) dominates the model — unsurprising, "
    "since past spend is usually the strongest signal of future spend."
)

st.divider()

# ==========================================================
# CUSTOMER LOOKUP
# ==========================================================

st.header("👤 Look Up a Customer")

selected_customer = st.selectbox(
    "Customer ID",
    sorted(prediction_df["CustomerID"].unique()),
)

customer = prediction_df[
    prediction_df["CustomerID"] == selected_customer
].iloc[0]

c1, c2, c3 = st.columns(3)
c1.metric("Segment", customer["CustomerSegment"])
c2.metric("Historical CLV", format_currency(customer["CLV"]))
c3.metric("Predicted CLV", format_currency(customer["PredictedCLV"]))