def sorted_unique(series):
    """
    Return sorted unique values from a column, safely.

    Some columns (like Country) can contain a missing value
    (NaN) for a handful of rows. sorted() cannot compare a
    float NaN with a string, which raises a TypeError. Dropping
    missing values before sorting avoids that.
    """

    return sorted(series.dropna().unique().tolist())

